"""`anona completion bash|zsh|fish`: a completion script generated from the parser.

Install:
    bash  anona completion bash > ~/.local/share/bash-completion/completions/anona
    zsh   anona completion zsh > "${fpath[1]}/_anona"   (or eval it from ~/.zshrc)
    fish  anona completion fish > ~/.config/fish/completions/anona.fish

Generated, not hand-written, so a new verb or flag completes the moment it
exists. Commands and flags complete; flag values do not, except where a flag
has fixed choices (fish only) -- a filename is offered where nothing else
fits.
"""

from __future__ import annotations

import argparse

from .introspect import Command, tree


def _quote(text: str) -> str:
    """Single-quoted for sh and fish: no expansion of any kind inside."""
    return "'" + text.replace("'", "'\\''") + "'"


def _paths(root: Command) -> list[Command]:
    return root.walk()


def _key(cmd: Command) -> str:
    # The root's path is ["anona"]; every other command's path starts at its own name.
    return "" if cmd.path == ["anona"] else " ".join(cmd.path)


def _flags(cmd: Command, root: Command) -> list[str]:
    flags = [f for o in cmd.options for f in o.flags]
    # Global flags are accepted after any command too.
    if cmd is not root:
        flags += [f for o in root.options for f in o.flags if f != "--version"]
    flags.append("--help")
    return flags


def bash(parser: argparse.ArgumentParser) -> str:
    root = tree(parser)
    children = []
    options = []
    for cmd in _paths(root):
        key = _quote(_key(cmd))
        if cmd.children:
            children.append(f"    {key}) echo {_quote(' '.join(c.path[-1] for c in cmd.children))};;")
        options.append(f"    {key}) echo {_quote(' '.join(_flags(cmd, root)))};;")
    return "\n".join(
        [
            "# anona completion for bash. Generated by `anona completion bash`.",
            "_anona_children() {",
            '  case "$1" in',
            *children,
            "  esac",
            "}",
            "_anona_options() {",
            '  case "$1" in',
            *options,
            "  esac",
            "}",
            "_anona() {",
            '  local cur="${COMP_WORDS[COMP_CWORD]}" path="" w i kids',
            "  for ((i=1; i<COMP_CWORD; i++)); do",
            '    w="${COMP_WORDS[i]}"',
            '    case "$w" in -*) continue;; esac',
            '    kids=" $(_anona_children "$path") "',
            '    if [[ "$kids" == *" $w "* ]]; then path="${path:+$path }$w"; fi',
            "  done",
            '  if [[ "$cur" == -* ]]; then',
            '    COMPREPLY=( $(compgen -W "$(_anona_options "$path")" -- "$cur") )',
            "  else",
            '    kids="$(_anona_children "$path")"',
            '    if [[ -n "$kids" ]]; then',
            '      COMPREPLY=( $(compgen -W "$kids" -- "$cur") )',
            "    else",
            '      COMPREPLY=( $(compgen -f -- "$cur") )',
            "    fi",
            "  fi",
            "}",
            "complete -o default -F _anona anona",
            "",
        ]
    )


def zsh(parser: argparse.ArgumentParser) -> str:
    # zsh runs the bash function through bashcompinit, which ships with zsh.
    # One generator for two shells means the two cannot disagree.
    return "\n".join(
        [
            "#compdef anona",
            "# anona completion for zsh. Generated by `anona completion zsh`.",
            "autoload -U +X bashcompinit && bashcompinit",
            bash(parser),
        ]
    )


def fish(parser: argparse.ArgumentParser) -> str:
    root = tree(parser)
    lines = ["# anona completion for fish. Generated by `anona completion fish`.", "complete -c anona -f"]
    top = " ".join(c.path[0] for c in root.children)
    for cmd in root.children:
        lines.append(
            f"complete -c anona -n {_quote('not __fish_seen_subcommand_from ' + top)} "
            f"-a {_quote(cmd.path[0])} -d {_quote(cmd.help[:80])}"
        )
    for opt in root.options:
        lines.extend(_fish_option(opt, None))
    for cmd in root.walk():
        if cmd is root:
            continue
        cond = " ; and ".join(f"__fish_seen_subcommand_from {p}" for p in cmd.path)
        if cmd.children:
            kids = " ".join(c.path[-1] for c in cmd.children)
            for child in cmd.children:
                lines.append(
                    f"complete -c anona -n {_quote(cond + ' ; and not __fish_seen_subcommand_from ' + kids)} "
                    f"-a {_quote(child.path[-1])} -d {_quote(child.help[:80])}"
                )
        for opt in cmd.options:
            lines.extend(_fish_option(opt, cond))
        if any(p.name in ("PATHS", "PATH") or "path" in p.help.lower() or "file" in p.help.lower() for p in cmd.positionals):
            lines.append(f"complete -c anona -n {_quote(cond)} -F")
    return "\n".join(lines) + "\n"


def _fish_option(opt, cond: str | None) -> list[str]:
    out = []
    for flag in opt.flags:
        if flag.startswith("--"):
            spec = f"-l {_quote(flag[2:])}"
        elif flag.startswith("-") and len(flag) == 2:
            spec = f"-s {_quote(flag[1:])}"
        else:
            continue
        line = "complete -c anona"
        if cond:
            line += f" -n {_quote(cond)}"
        line += f" {spec}"
        if opt.takes_value:
            line += " -r"
            if opt.choices:
                line += f" -a {_quote(' '.join(opt.choices))}"
        if opt.help:
            line += f" -d {_quote(opt.help[:80])}"
        out.append(line)
    return out


def script(parser: argparse.ArgumentParser, shell: str) -> str:
    return {"bash": bash, "zsh": zsh, "fish": fish}[shell](parser)
