/**
 * `anona-memory completion bash|zsh|fish`: a completion script generated from the
 * command registry. Mirrors anona/cli/completion.py and prints the same script.
 *
 * Install:
  *   bash  anona-memory completion bash > ~/.local/share/bash-completion/completions/anona-memory
  *   zsh   anona-memory completion zsh > "${fpath[1]}/_anona-memory"   (or eval it from ~/.zshrc)
  *   fish  anona-memory completion fish > ~/.config/fish/completions/anona-memory.fish
 *
 * Generated, not hand-written, so a new verb or flag completes the moment it
 * exists. Commands and flags complete; flag values do not, except where a flag
 * has fixed choices (fish only) -- a filename is offered where nothing else fits.
 */
import { tree, walk, type TreeCommand, type TreeOption } from "./args.js";

/** Single-quoted for sh and fish: no expansion of any kind inside. */
function quote(text: string): string {
  return "'" + text.split("'").join("'\\''") + "'";
}

const keyOf = (cmd: TreeCommand) => (cmd.path.length === 1 && cmd.path[0] === "anona-memory" ? "" : cmd.path.join(" "));

function flags(cmd: TreeCommand, root: TreeCommand): string[] {
  const out = cmd.options.flatMap((o) => o.flags);
  // Global flags are accepted after any command too.
  if (cmd !== root) out.push(...root.options.flatMap((o) => o.flags).filter((f) => f !== "--version"));
  out.push("--help");
  return out;
}

const cut = (s: string) => Array.from(s).slice(0, 80).join("");

export function bash(): string {
  const root = tree();
  const children: string[] = [];
  const options: string[] = [];
  for (const cmd of walk(root)) {
    const key = quote(keyOf(cmd));
    if (cmd.children.length) children.push(`    ${key}) echo ${quote(cmd.children.map((c) => c.path[c.path.length - 1]).join(" "))};;`);
    options.push(`    ${key}) echo ${quote(flags(cmd, root).join(" "))};;`);
  }
  return [
    "# anona-memory completion for bash. Generated by `anona-memory completion bash`.",
    "_anona_memory_children() {",
    '  case "$1" in',
    ...children,
    "  esac",
    "}",
    "_anona_memory_options() {",
    '  case "$1" in',
    ...options,
    "  esac",
    "}",
    "_anona_memory() {",
    '  local cur="${COMP_WORDS[COMP_CWORD]}" path="" w i kids',
    "  for ((i=1; i<COMP_CWORD; i++)); do",
    '    w="${COMP_WORDS[i]}"',
    '    case "$w" in -*) continue;; esac',
    '    kids=" $(_anona_memory_children "$path") "',
    '    if [[ "$kids" == *" $w "* ]]; then path="${path:+$path }$w"; fi',
    "  done",
    '  if [[ "$cur" == -* ]]; then',
    '    COMPREPLY=( $(compgen -W "$(_anona_memory_options "$path")" -- "$cur") )',
    "  else",
    '    kids="$(_anona_memory_children "$path")"',
    '    if [[ -n "$kids" ]]; then',
    '      COMPREPLY=( $(compgen -W "$kids" -- "$cur") )',
    "    else",
    '      COMPREPLY=( $(compgen -f -- "$cur") )',
    "    fi",
    "  fi",
    "}",
    "complete -o default -F _anona_memory anona-memory",
    "",
  ].join("\n");
}

/** zsh runs the bash function through bashcompinit: one generator, two shells that cannot disagree. */
export function zsh(): string {
  return ["#compdef anona-memory", "# anona-memory completion for zsh. Generated by `anona-memory completion zsh`.", "autoload -U +X bashcompinit && bashcompinit", bash()].join("\n");
}

function fishOption(o: TreeOption, cond: string | null): string[] {
  const out: string[] = [];
  for (const flag of o.flags) {
    let spec: string;
    if (flag.startsWith("--")) spec = `-l ${quote(flag.slice(2))}`;
    else if (flag.startsWith("-") && flag.length === 2) spec = `-s ${quote(flag.slice(1))}`;
    else continue;
    let line = "complete -c anona-memory";
    if (cond) line += ` -n ${quote(cond)}`;
    line += ` ${spec}`;
    if (o.takes_value) {
      line += " -r";
      if (o.choices) line += ` -a ${quote(o.choices.join(" "))}`;
    }
    if (o.help) line += ` -d ${quote(cut(o.help))}`;
    out.push(line);
  }
  return out;
}

export function fish(): string {
  const root = tree();
  const lines = ["# anona-memory completion for fish. Generated by `anona-memory completion fish`.", "complete -c anona-memory -f"];
  const top = root.children.map((c) => c.path[0]).join(" ");
  for (const cmd of root.children) {
    lines.push(
      `complete -c anona-memory -n ${quote("not __fish_seen_subcommand_from " + top)} -a ${quote(cmd.path[0] as string)} -d ${quote(cut(cmd.help))}`,
    );
  }
  for (const o of root.options) lines.push(...fishOption(o, null));
  for (const cmd of walk(root)) {
    if (cmd === root) continue;
    const cond = cmd.path.map((p) => `__fish_seen_subcommand_from ${p}`).join(" ; and ");
    if (cmd.children.length) {
      const kids = cmd.children.map((c) => c.path[c.path.length - 1]).join(" ");
      for (const child of cmd.children) {
        lines.push(
          `complete -c anona-memory -n ${quote(cond + " ; and not __fish_seen_subcommand_from " + kids)} ` +
            `-a ${quote(child.path[child.path.length - 1] as string)} -d ${quote(cut(child.help))}`,
        );
      }
    }
    for (const o of cmd.options) lines.push(...fishOption(o, cond));
    if (
      cmd.positionals.some(
        (p) => p.name === "PATHS" || p.name === "PATH" || p.help.toLowerCase().includes("path") || p.help.toLowerCase().includes("file"),
      )
    ) {
      lines.push(`complete -c anona-memory -n ${quote(cond)} -F`);
    }
  }
  return lines.join("\n") + "\n";
}

export function script(shell: string): string {
  return shell === "bash" ? bash() : shell === "zsh" ? zsh() : fish();
}
